/**
 * The app's copy of the HRS Nexus UI theme, generated from its one source, the design system
 * (../design-system: tokens.json and components/bundle.css), into ../assets/styles/nexus:
 *
 * - `tokens.css`: every token as a CSS custom property. The colour and shadow roles per theme
 *   (`:root` and `[data-theme="purple"]` first, then one block per base theme), the rest once on
 *   `:root`; the type styles as font shorthands (`--hrs-font-<style>`) and trackings
 *   (`--hrs-tracking-<style>`), not classes, so they never clash with the app's own class names.
 * - `nexus.css`: bundle.css without the preview-only helpers (the scene stand-in and the preview
 *   rows), without its font import (the app's index.html loads the fonts), and with the game
 *   textures it embeds as data URIs read from custom properties instead (`--hrs-tex-<texture>`),
 *   which the shell sets from the interface sheet.
 *
 *   pnpm run generate.theme
 *
 * Never edit the generated files: change the design system and run this again.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import postcss from 'postcss';
import prettier from 'prettier';

const root = join(import.meta.dirname, '..');
const source = join(root, 'design-system');
const out = join(root, 'assets', 'styles', 'nexus');

/** Rules in bundle.css that only the previews use. */
const PREVIEW_ONLY = new Set(['.hrs-stage', '.hrs-stage--flush', '.hrs-row-flex', '.hrs-col']);

type PerTheme = string | Readonly<Record<string, string>>;
interface Token {
  readonly name: string;
  readonly value: PerTheme;
}
interface TypeStyle {
  readonly name: string;
  readonly family?: string;
  readonly fontSize: string;
  readonly lineHeight?: string;
  readonly fontWeight?: number;
  readonly letterSpacing?: string;
}
interface Tokens {
  readonly name: string;
  readonly color: { readonly themes: readonly { readonly id: string }[]; readonly tokens: readonly Token[] };
  readonly shadow: { readonly tokens: readonly Token[] };
  readonly spacing: { readonly tokens: readonly Token[] };
  readonly radius: { readonly tokens: readonly Token[] };
  readonly opacity: { readonly tokens: readonly Token[] };
  readonly effect: { readonly tokens: readonly Token[] };
  readonly type: {
    readonly families: Readonly<Record<string, string>>;
    readonly groups: readonly { readonly family: string; readonly styles: readonly TypeStyle[] }[];
  };
}

const HEADER = (what: string) =>
  `/* ${what}: generated by \`pnpm run generate.theme\` (packages/common/tools/generate-theme.ts) from packages/common/design-system. Do not edit. */\n`;

/** The game texture's custom property: `storm_ui_triangle_mask` → `--hrs-tex-triangle-mask`. */
function textureProperty(texture: string): string {
  return `--hrs-tex-${texture.replace(/^storm_ui_/, '').replaceAll('_', '-')}`;
}

function tokensCss(t: Tokens): string {
  const themes = t.color.themes.map((x) => x.id);
  const first = themes[0]!;
  const value = (token: Token, theme: string) =>
    typeof token.value === 'string' ? token.value : (token.value[theme] ?? token.value[first]);
  const blocks = themes.map((theme) => {
    const selector = theme === first ? `:root, [data-theme="${theme}"]` : `[data-theme="${theme}"]`;
    const lines = [...t.color.tokens, ...t.shadow.tokens].map(
      (token) => `  --${token.name}: ${value(token, theme)};`,
    );
    return `${selector} {\n${lines.join('\n')}\n}`;
  });
  const once = [t.spacing, t.radius, t.opacity, t.effect].flatMap((family) =>
    family.tokens.map((token) => `  --${token.name}: ${value(token, first)};`),
  );
  const families = Object.entries(t.type.families).map(([k, v]) => `  --font-${k}: ${v};`);
  const styles = t.type.groups.flatMap((group) =>
    group.styles.flatMap((s) => {
      const font = `${s.fontWeight ?? 400} ${s.fontSize}/${s.lineHeight ?? 'normal'} var(--font-${s.family ?? group.family})`;
      const lines = [`  --hrs-font-${s.name}: ${font};`];
      if (s.letterSpacing !== undefined) lines.push(`  --hrs-tracking-${s.name}: ${s.letterSpacing};`);
      return lines;
    }),
  );
  return `${HEADER(`${t.name} tokens`)}${blocks.join('\n')}\n:root {\n${[...once, ...families, ...styles].join('\n')}\n}\n`;
}

function bundleCss(css: string, textures: ReadonlyMap<string, string>): string {
  const tree = postcss.parse(css);
  tree.walkAtRules('import', (rule) => {
    rule.remove();
  });
  tree.each((node) => {
    if (node.type === 'rule' && node.selectors.every((s) => PREVIEW_ONLY.has(s))) {
      // its comment goes with it
      const before = node.prev();
      if (before?.type === 'comment' && /preview/i.test(before.text)) before.remove();
      node.remove();
    }
  });
  const unknown: string[] = [];
  tree.walkDecls((decl) => {
    decl.value = decl.value.replace(/url\("(data:[^"]+)"\)/g, (_, uri: string) => {
      const texture = textures.get(uri);
      if (!texture) {
        unknown.push(`${decl.parent && 'selector' in decl.parent ? decl.parent.selector : '?'} ${decl.prop}`);
        return 'none';
      }
      return `var(${textureProperty(texture)})`;
    });
  });
  if (unknown.length)
    throw new Error(`bundle.css embeds pictures build/tex_uris.json doesn't name: ${unknown.join('; ')}`);
  tree.walkRules((rule) => {
    const helper = rule.selectors.find((s) => PREVIEW_ONLY.has(s));
    if (helper) throw new Error(`a rule mixes the preview helper ${helper} with others: ${rule.selector}`);
  });
  return `${HEADER('HRS Nexus UI components')}${tree.toString().trimStart()}`;
}

async function format(file: string, css: string): Promise<string> {
  const options = await prettier.resolveConfig(file);
  return prettier.format(css, { ...options, filepath: file });
}

const tokens = JSON.parse(await readFile(join(source, 'tokens.json'), 'utf8')) as Tokens;
const textures = new Map(
  Object.entries(
    JSON.parse(await readFile(join(source, 'build', 'tex_uris.json'), 'utf8')) as Record<string, unknown>,
  ).flatMap(([name, uri]) => (typeof uri === 'string' ? [[uri, name] as const] : [])),
);
const bundle = await readFile(join(source, 'components', 'bundle.css'), 'utf8');

await mkdir(out, { recursive: true });
for (const [name, css] of [
  ['tokens.css', tokensCss(tokens)],
  ['nexus.css', bundleCss(bundle, textures)],
] as const) {
  const file = join(out, name);
  await writeFile(file, await format(file, css));
  console.log(`wrote ${file}`);
}
